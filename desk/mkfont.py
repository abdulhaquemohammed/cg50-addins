# Build calc font: gint 8x9 ASCII glyphs + custom maths symbols in 0x03-0x1F
from PIL import Image
import sys

src = Image.open(sys.argv[1]).convert("RGB")
out = Image.new("RGB", (160, 104), (255, 255, 255))
# copy printable ASCII (0x20..0x7E) to rows 2..7
for i in range(95):
    r, c = divmod(i, 16)
    cell = src.crop((c * 10, r * 13, c * 10 + 10, r * 13 + 13))
    code = 0x20 + i
    R, Cc = divmod(code, 16)
    out.paste(cell, (Cc * 10, R * 13))

