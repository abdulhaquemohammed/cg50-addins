px = out.load()
for code in range(0x00, 0x20):
    R, Cc = divmod(code, 16)
    x0, y0 = Cc * 10 + 1, R * 13 + 1
    g = G.get(code)
    if isinstance(g, tuple):
        g = g[0]
    if not g:
        px[x0, y0 + 8] = (170, 170, 170)
        continue
    for y, row in enumerate(g.split("\n")):
        for x, ch in enumerate(row):
            if ch == "#":
                px[x0 + x, y0 + y] = (0, 0, 0)
